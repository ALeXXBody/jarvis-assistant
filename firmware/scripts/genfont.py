#!/usr/bin/env python3
"""Generate an anti-aliased bitmap font header for the panel UI.

Reads DejaVuSans.ttf, renders ASCII 32..126 at fixed pixel sizes with an
8-bit alpha channel, and emits src/jarvis_font.h with metrics + rasters.

The generated header is committed to the repo so firmware builds need no
Python. Regenerate with:  python3 scripts/genfont.py
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SRC = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
OUT = "src/jarvis_font.h"
SIZES = [26, 34, 56]
FIRST, LAST = 32, 126

def glyphs_for(size):
    font = ImageFont.truetype(SRC, size)
    out = []
    for ch in range(FIRST, LAST + 1):
        c = chr(ch)
        adv = font.getlength(c)
        bbox = font.getbbox(c, anchor="ls")
        x0, y0, x1, y1 = bbox
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        img = Image.new("L", (w, h), 0)
        if w and h:
            d = ImageDraw.Draw(img)
            d.text((-x0, -y0), c, font=font, fill=255, anchor="ls")
        out.append({
            "adv": int(round(adv)), "data": img.tobytes(),
            "xoff": x0, "yoff": y0, "w": w, "h": h,
        })
    return out

def main():
    rows = []
    data_off = 0
    all_data = bytearray()
    tables = []
    for si, size in enumerate(SIZES):
        gs = glyphs_for(size)
        entries = []
        for g in gs:
            entries.append(
                "    {%d, %d, %d, %d, %d, %d},"
                % (g["xoff"], g["yoff"], g["w"], g["h"], g["adv"], data_off))
            all_data += g["data"]
            data_off += len(g["data"])
        tables.append((size, entries))

    with open(OUT, "w") as f:
        f.write("/*\n * Anti-aliased UI font — generated by scripts/genfont.py\n")
        f.write(" * (DejaVu Sans, sizes %s, ASCII 32..126, 8-bit alpha).\n" % SIZES)
        f.write(" * Baseline-anchored: yoff of a glyph is relative to its baseline.\n */\n")
        f.write("#pragma once\n\n#include <stdint.h>\n\n")
        f.write("#define JF_N_SIZES %d\n" % len(SIZES))
        f.write("#define JF_SIZE_0 %d  /* labels/status */\n" % SIZES[0])
        f.write("#define JF_SIZE_1 %d  /* body         */\n" % SIZES[1])
        f.write("#define JF_SIZE_2 %d  /* state word   */\n" % SIZES[2])
        f.write("#define JF_N_GLYPHS %d /* ascii 32..126 */\n\n" % (LAST - FIRST + 1))
        f.write("typedef struct {\n"
                "    int16_t  xoff;      /* pen offset x                                 */\n"
                "    int16_t  yoff;      /* top of bitmap relative to the baseline       */\n"
                "    uint16_t w, h;\n"
                "    uint8_t  adv;       /* per-char advance (error <=1 px / original)  */\n"
                "    uint32_t data_off;  /* byte offset into jf_raster[] (raster>64KB)  */\n"
                "} jf_glyph_t;\n\n")
        # metrics per size
        mets = []
        for si, size in enumerate(SIZES):
            font = ImageFont.truetype(SRC, size)
            asc, desc = font.getmetrics()
            mets.append((asc, desc))
        f.write("static const uint8_t jf_ascent[JF_N_SIZES]  __attribute__((unused)) =\n")
        f.write("    { %s };\n" % ", ".join(str(a) for a, _ in mets))
        f.write("static const uint8_t jf_descent[JF_N_SIZES] __attribute__((unused)) =\n")
        f.write("    { %s };\n\n" % ", ".join(str(d) for _, d in mets))
        f.write("extern const uint8_t jf_raster[%d];\n\n" % len(all_data))
        f.write("static const uint8_t jf_raster_data[%d] __attribute__((unused)) = {\n"
                % len(all_data))
        for i in range(0, len(all_data), 16):
            f.write("    " + ",".join(str(b) for b in all_data[i:i + 16]) + ",\n")
        f.write("};\n\n")
        f.write("static const jf_glyph_t jf_glyphs[JF_N_SIZES][JF_N_GLYPHS]"
                " __attribute__((unused)) = {\n")
        for size, entries in tables:
            f.write("    { /* size %d */\n" % size)
            for e in entries:
                f.write(e + "\n")
            f.write("    },\n")
        f.write("};\n")

    print("wrote %s: %d bytes of raster" % (OUT, len(all_data)))

if __name__ == "__main__":
    sys.exit(main())
